/**
 * @fileoverview Root application component.
 * Orchestrates all plan sections and manages global state.
 */

import { useState, useCallback } from 'react';
import Header from './components/Header.jsx';
import EventForm from './components/EventForm.jsx';
import BudgetBreakdown from './components/BudgetBreakdown.jsx';
import Timeline from './components/Timeline.jsx';
import VendorChecklist from './components/VendorChecklist.jsx';
import IdeasPanel from './components/IdeasPanel.jsx';

/**
 * @typedef {object} EventPlan
 * @property {string} eventType
 * @property {number} budget
 * @property {number} guestCount
 * @property {Date}   eventDate
 * @property {string} city
 * @property {string} theme
 */

/**
 * Format the complete plan as plain text for clipboard copy.
 *
 * @param {EventPlan} plan
 * @returns {string}
 */
function formatPlanAsText(plan) {
  const lines = [
    '═══════════════════════════════════════',
    '           🎉 PARTYPILOT PLAN 🎉',
    '═══════════════════════════════════════',
    '',
    `Event Type : ${plan.eventType.charAt(0).toUpperCase() + plan.eventType.slice(1)}`,
    `City       : ${plan.city}`,
    `Date       : ${plan.eventDate.toLocaleDateString('en-IN', { weekday: 'long', day: 'numeric', month: 'long', year: 'numeric' })}`,
    `Budget     : ₹${plan.budget.toLocaleString('en-IN')}`,
    `Guests     : ${plan.guestCount.toLocaleString('en-IN')}`,
    `Theme      : ${plan.theme}`,
    '',
    '─── Generated by PartyPilot ───',
    'https://partypilot.vercel.app',
  ];
  return lines.join('\n');
}

/**
 * Root application component.
 * @returns {JSX.Element}
 */
export default function App() {
  /** @type {[EventPlan|null, Function]} */
  const [plan, setPlan] = useState(null);
  const [copyStatus, setCopyStatus] = useState('idle'); // 'idle' | 'copied' | 'error'

  /**
   * Handle plan generation from EventForm.
   * @param {EventPlan} formData
   */
  const handlePlanSubmit = useCallback((formData) => {
    setPlan(formData);
    setCopyStatus('idle');
    // Scroll to budget section after a short delay for DOM update
    setTimeout(() => {
      document.getElementById('budget-section')?.scrollIntoView({ behavior: 'smooth' });
    }, 100);
  }, []);

  /**
   * Copy the full plan as plain text to the clipboard.
   */
  const handleCopyPlan = useCallback(async () => {
    if (!plan) return;
    try {
      await navigator.clipboard.writeText(formatPlanAsText(plan));
      setCopyStatus('copied');
      setTimeout(() => setCopyStatus('idle'), 3000);
    } catch {
      setCopyStatus('error');
      setTimeout(() => setCopyStatus('idle'), 3000);
    }
  }, [plan]);

  const copyLabel =
    copyStatus === 'copied'
      ? '✅ Copied!'
      : copyStatus === 'error'
      ? '❌ Copy failed'
      : '📋 Copy Plan';

  return (
    <div className="app-wrapper">
      <Header hasPlan={!!plan} />

      <main id="main-content" className="main-content">
        <div className="container">
          {/* Event Form — always visible */}
          <EventForm onSubmit={handlePlanSubmit} />

          {/* Plan sections — only shown after form submit */}
          {plan && (
            <>
              {/* Copy Plan CTA */}
              <div className="copy-plan-row">
                <button
                  id="btn-copy-plan"
                  className="btn-primary btn-copy"
                  onClick={handleCopyPlan}
                  aria-label={copyLabel}
                  aria-live="polite"
                >
                  {copyLabel}
                </button>
              </div>

              <BudgetBreakdown
                eventType={plan.eventType}
                budget={plan.budget}
                guestCount={plan.guestCount}
              />

              <Timeline
                eventDate={plan.eventDate}
                eventType={plan.eventType}
              />

              <VendorChecklist eventType={plan.eventType} />

              <IdeasPanel
                eventType={plan.eventType}
                theme={plan.theme}
                city={plan.city}
                budget={plan.budget}
                guestCount={plan.guestCount}
              />
            </>
          )}
        </div>
      </main>

      <footer className="app-footer" role="contentinfo">
        <p>
          Made with <span aria-label="love">💜</span> by PartyPilot •{' '}
          <span aria-hidden="true">🤖</span> Powered by Gemini AI
        </p>
      </footer>
    </div>
  );
}
